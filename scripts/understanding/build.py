"""Build original chapter concept checks; never alters existing textbook exercises."""
from pathlib import Path
import json, collections
ROOT=Path(__file__).resolve().parents[2]
DATA=Path(__file__).parent
refs=json.loads((DATA/'chapter-reference.json').read_text())
extra={}
for subject in ['calculus','physics','chemistry','organic','linear-algebra']:
    chapter=None; entries=[]; counts=collections.Counter()
    for raw in (DATA/(subject+'.tsv')).read_text().splitlines():
        if raw.startswith('# '):
            chapter=int(raw[2:]); continue
        if not raw.strip(): continue
        statement,truth,explanation=raw.split('|')
        assert truth in ('T','F')
        assert len(statement)>10 and len(explanation)>25
        assert chapter in {q[0] for q in refs[subject]}
        counts[chapter]+=1
        qid=f'{subject}-{chapter}-concept-{counts[chapter]}'
        entries.append([chapter,'Is this statement correct? '+statement,['Yes — the statement is correct.','No — the statement needs correcting.'],0 if truth=='T' else 1,explanation,explanation,qid])
    assert set(counts)=={q[0] for q in refs[subject]},(subject,counts)
    assert all(v==9 for v in counts.values()),(subject,counts)
    assert len({q[1] for q in entries})==len(entries),(subject,'duplicate statements')
    extra[subject]=entries
# This subject deliberately shares the calculus textbook chapters. Reuse stable IDs
# so an identical concept check has one saved completion, with no key collisions.
extra['differential-equations']=[q for q in extra['calculus'] if q[0] in (9,17)]
content='/* Original Glasshouse chapter checks; generated by scripts/understanding/build.py. */\n'
content+='(()=>{const additions='+json.dumps(extra,ensure_ascii=False,separators=(',',':'))+';\n'
content+='window.UNDERSTANDING_EXTRA=window.UNDERSTANDING_EXTRA||{};for(const [book,rows] of Object.entries(additions)){window.UNDERSTANDING_EXTRA[book]=[...(window.UNDERSTANDING_EXTRA[book]||[]),...rows];}})();\n'
(ROOT/'site/understanding-chapters.js').write_text(content)
report={'chapterEntries':sum(len(v) for v in refs.values()),'newChecks':sum(len(v) for v in extra.values()),'uniqueNewChecks':len({q[6] for rows in extra.values() for q in rows}),'minimumAddedPerChapter':9,'existingChecksPreserved':True,'format':'Original true/false concept checks with explanatory answer feedback, in addition to existing multiple-choice checks','subjects':{b:{str(c[0]):sum(q[0]==c[0] for q in extra[b]) for c in chapters}for b,chapters in refs.items()}}
(DATA/'coverage.json').write_text(json.dumps(report,indent=2)+'\n')
print(json.dumps({k:report[k]for k in ['chapterEntries','newChecks','uniqueNewChecks']}))
